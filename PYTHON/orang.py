class Orang:
    def __init__(self, nik, nama, jenis_kelamin):
        self.nik = nik
        self.nama = nama
        self.jenis_kelamin = jenis_kelamin

    def get_nik(self): return self.nik
    def get_nama(self): return self.nama
    def get_jenis_kelamin(self): return self.jenis_kelamin